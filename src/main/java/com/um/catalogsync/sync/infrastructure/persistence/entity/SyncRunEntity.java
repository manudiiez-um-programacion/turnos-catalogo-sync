package com.um.catalogsync.sync.infrastructure.persistence.entity;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.Table;
import java.time.Instant;
import lombok.AllArgsConstructor;
import lombok.Builder;
import lombok.Getter;
import lombok.NoArgsConstructor;
import lombok.Setter;

/**
 * Representacion JPA de una corrida de sincronizacion.
 *
 * <p>A diferencia de {@code CatalogVersionEntity}, acá el id si lo genera la
 * base: la tabla guarda una coleccion de intentos, no un unico valor.
 * {@code GenerationType.IDENTITY} acompaña al
 * {@code GENERATED BY DEFAULT AS IDENTITY} de la migracion.
 *
 * <p>Los tres enums se guardan como texto y la conversion pasa por el
 * mapper, no por {@code Enum.valueOf} dentro de Hibernate: es el mismo
 * criterio que en {@code CatalogVersionEntity} y {@code WeeklyScheduleEntity}
 * —la entidad JPA no lleva tipos de dominio—. Los {@code length} acompañan
 * los {@code VARCHAR} de la migracion, que ademas tienen un CHECK con los
 * literales validos.
 *
 * <p>{@code fromVersion}, {@code toVersion} y {@code finishedAt} son
 * objetos y no primitivos porque las tres columnas son nulables, y los tres
 * nulos significan algo: no habia version previa, no se llego a ninguna
 * version, todavia no termino.
 */
@Entity
@Table(name = "sync_run")
@Getter
@Setter
@Builder
@NoArgsConstructor
@AllArgsConstructor
public class SyncRunEntity {

    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    @Column(name = "id", nullable = false)
    private Long id;

    @Column(name = "mode", nullable = false, length = 16)
    private String mode;

    /**
     * {@code triggered_by} y no {@code trigger}: TRIGGER es palabra
     * reservada en PostgreSQL, como anota la migracion.
     */
    @Column(name = "triggered_by", nullable = false, length = 32)
    private String triggeredBy;

    @Column(name = "status", nullable = false, length = 16)
    private String status;

    @Column(name = "from_version")
    private Long fromVersion;

    @Column(name = "to_version")
    private Long toVersion;

    @Column(name = "started_at", nullable = false)
    private Instant startedAt;

    @Column(name = "finished_at")
    private Instant finishedAt;
}
