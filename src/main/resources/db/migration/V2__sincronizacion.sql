-- Estado de la sincronizacion con la catedra.
--
-- Separado de V1 a proposito: V1 es la copia del catalogo (datos de la
-- catedra, con la forma del contrato) y V2 es el estado propio de este
-- servicio (que version aplicamos, que eventos ya procesamos, como salieron
-- las corridas). Son dos cosas con ciclos de vida distintos.


-- --- Version de catalogo aplicada ---------------------------------------
--
-- Una sola fila: la version local es un unico valor para el servicio. El
-- CHECK sobre un id fijo lo hace imposible de violar, en lugar de confiar en
-- que el codigo nunca inserte una segunda fila.
--
-- La regla no negociable del proyecto es que esta fila avanza SOLO cuando la
-- unidad de trabajo termino completa: un snapshot aplicado entero, o todos
-- los cambios de una version. Por eso vive en la misma base y la misma
-- transaccion que los datos: si el commit falla, la version no avanzo.
CREATE TABLE catalog_version (
    id              SMALLINT     NOT NULL,
    applied_version BIGINT       NOT NULL,
    applied_at      TIMESTAMPTZ  NOT NULL,
    -- Como se llego a esta version: SNAPSHOT (sincronizacion completa) o
    -- INCREMENTAL (cambios leidos de Redis). Es vocabulario nuestro, no del
    -- contrato, asi que se puede restringir.
    source          VARCHAR(16)  NOT NULL,

    CONSTRAINT pk_catalog_version PRIMARY KEY (id),
    CONSTRAINT ck_catalog_version_single_row CHECK (id = 1),
    CONSTRAINT ck_catalog_version_source CHECK (source IN ('SNAPSHOT', 'INCREMENTAL')),
    CONSTRAINT ck_catalog_version_not_negative CHECK (applied_version >= 0)
);

COMMENT ON TABLE catalog_version IS
    'Version de catalogo aplicada. Una sola fila (id = 1). Avanza solo al terminar la unidad de trabajo.';


-- --- Eventos ya procesados ----------------------------------------------
--
-- Deduplicacion de CatalogUpdated por eventId (§15.3). El event_id es la
-- clave primaria y no una columna con indice unico aparte: asi insertar es
-- la operacion que decide si el evento es nuevo. Un INSERT que choca con la
-- PK significa "ya procesado", sin consultar antes y sin ventana de carrera
-- entre el SELECT y el INSERT.
CREATE TABLE processed_event (
    event_id     VARCHAR(255) NOT NULL,
    event_type   VARCHAR(64)  NOT NULL,
    new_version  BIGINT       NOT NULL,
    occurred_at  TIMESTAMPTZ  NOT NULL,
    -- Origen que informa la catedra, por ejemplo MANUAL o SCHEDULED (§15.3).
    -- Sin CHECK: es vocabulario de la catedra y puede crecer sin avisarnos.
    -- Restringirlo seria inventar una regla que el contrato no da.
    source       VARCHAR(64),
    processed_at TIMESTAMPTZ  NOT NULL,

    CONSTRAINT pk_processed_event PRIMARY KEY (event_id)
);

COMMENT ON TABLE processed_event IS
    'CatalogUpdated ya procesados, deduplicados por eventId (§15.3).';
COMMENT ON COLUMN processed_event.source IS
    'Valor informado por la catedra (MANUAL, SCHEDULED, ...). Sin restriccion: vocabulario externo.';

-- Para responder "cual fue el ultimo evento de esta version" al reconciliar.
CREATE INDEX ix_processed_event_new_version
    ON processed_event (new_version);


-- --- Corridas de sincronizacion -----------------------------------------
--
-- Alimentan el endpoint de estado y errores (#28). Una fila por intento, con
-- el rango de versiones que cubrio.
CREATE TABLE sync_run (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY,
    mode         VARCHAR(16)  NOT NULL,
    -- triggered_by y no "trigger": TRIGGER es palabra reservada en
    -- PostgreSQL y obligaria a citar la columna en cada consulta.
    triggered_by VARCHAR(32)  NOT NULL,
    status       VARCHAR(16)  NOT NULL,
    -- Nulos mientras no se sepa: al arrancar con base vacia no hay version
    -- de origen, y to_version solo se conoce si la corrida termino bien.
    from_version BIGINT,
    to_version   BIGINT,
    started_at   TIMESTAMPTZ  NOT NULL,
    finished_at  TIMESTAMPTZ,

    CONSTRAINT pk_sync_run PRIMARY KEY (id),
    CONSTRAINT ck_sync_run_mode CHECK (mode IN ('FULL', 'INCREMENTAL')),
    CONSTRAINT ck_sync_run_status CHECK (status IN ('RUNNING', 'SUCCEEDED', 'FAILED')),
    CONSTRAINT ck_sync_run_triggered_by CHECK (triggered_by IN (
        'STARTUP', 'EVENT', 'RECONCILIATION', 'DISCONTINUITY', 'MANUAL'
    )),
    -- Una corrida en curso no tiene fin; una terminada si.
    CONSTRAINT ck_sync_run_finished_at CHECK (
        (status = 'RUNNING' AND finished_at IS NULL)
        OR (status <> 'RUNNING' AND finished_at IS NOT NULL)
    )
);

COMMENT ON TABLE sync_run IS
    'Una fila por intento de sincronizacion. Alimenta el estado que expone #28.';

-- La consulta tipica del endpoint de estado es "las ultimas corridas".
CREATE INDEX ix_sync_run_started_at ON sync_run (started_at DESC);


-- --- Errores de sincronizacion ------------------------------------------
--
-- Aca si hay ON DELETE CASCADE, y es el caso en el que corresponde: un error
-- no tiene sentido sin su corrida, no es una entidad con vida propia. Es lo
-- contrario de las tablas de catalogo, donde un borrado en cascada
-- destruiria datos reales.
CREATE TABLE sync_error (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY,
    sync_run_id BIGINT       NOT NULL,
    occurred_at TIMESTAMPTZ  NOT NULL,
    -- Codigo estable, propio del servicio, para que el error se pueda
    -- identificar sin parsear el mensaje (§13 pide codigos estables).
    code        VARCHAR(64)  NOT NULL,
    detail      TEXT,

    CONSTRAINT pk_sync_error PRIMARY KEY (id),
    CONSTRAINT fk_sync_error_run FOREIGN KEY (sync_run_id)
        REFERENCES sync_run (id)
        ON DELETE CASCADE
);

COMMENT ON TABLE sync_error IS
    'Errores de una corrida de sincronizacion. Se borran con ella.';

CREATE INDEX ix_sync_error_run ON sync_error (sync_run_id);
