package com.um.catalogsync.sync.domain.model;

import java.time.Instant;
import lombok.AllArgsConstructor;
import lombok.Builder;
import lombok.Getter;
import lombok.NoArgsConstructor;
import lombok.Setter;

/**
 * Un intento de sincronizacion: cuando arranco, por que, como termino y
 * entre que versiones.
 *
 * <p>Es el historial que alimenta el estado y los errores de
 * sincronizacion (#28), y lo que el enunciado pide poder informar. Hay una
 * fila por <b>intento</b>, no por exito: una corrida que falla deja su
 * rastro, que es justamente el caso en el que el registro sirve.
 *
 * <p><b>Es estado propio, no de la catedra.</b> Ninguno de estos datos
 * viene del contrato: el reloj es nuestro, el motivo es nuestra decision y
 * el resultado es nuestro. Por eso vive en {@code sync_run} y no junto a la
 * copia del catalogo.
 *
 * <p>POJO puro, igual que el resto de los modelos: sin JPA, sin validacion,
 * sin Jackson.
 *
 * <p><b>Que esta clase deliberadamente no hace: cambiar de estado.</b> No
 * hay {@code marcarExitosa()} ni un setter de estado que alguien pueda usar
 * suelto. Las transiciones viven en el puerto
 * {@code SyncRunRepository}, cuyas operaciones escriben siempre el estado y
 * el instante de fin juntos. Asi la invariante de la tabla —RUNNING sin
 * fin, terminadas con fin— no depende de que nadie se olvide: no existe la
 * forma de romperla.
 */
@Getter
@Setter
@Builder
@NoArgsConstructor
@AllArgsConstructor
public class SyncRun {

    /** Lo asigna la base: {@code GENERATED BY DEFAULT AS IDENTITY}. */
    private Long id;

    private SyncMode mode;

    /** El "motivo" del enunciado: por que arranco esta corrida. */
    private SyncTrigger triggeredBy;

    private SyncStatus status;

    /**
     * Version local al empezar, o {@code null} si la base estaba recien
     * inicializada.
     *
     * <p>El {@code null} es informacion y no un hueco: distingue "veniamos
     * de la version 5" de "no teniamos ninguna version", que es la
     * situacion que dispara la primera sincronizacion completa (#14).
     */
    private Long fromVersion;

    /**
     * Version a la que se llego, o {@code null} si la corrida no termino o
     * termino mal.
     *
     * <p>Que sea {@code null} en las corridas fallidas no es un detalle de
     * registro: es la regla no negociable del proyecto vista desde el
     * historial. Si una corrida fallida tuviera {@code toVersion}, estaria
     * afirmando que la copia local llego a una version que nunca aplico.
     */
    private Long toVersion;

    private Instant startedAt;

    /** Cuando termino, o {@code null} si sigue corriendo. */
    private Instant finishedAt;

    /** @return si todavia no termino */
    public boolean isRunning() {
        return status == SyncStatus.RUNNING;
    }

    /** @return si termino, haya salido bien o mal */
    public boolean isFinished() {
        return status == SyncStatus.SUCCEEDED || status == SyncStatus.FAILED;
    }
}
