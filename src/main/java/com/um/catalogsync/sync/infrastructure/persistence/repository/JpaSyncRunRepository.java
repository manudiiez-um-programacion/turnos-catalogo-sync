package com.um.catalogsync.sync.infrastructure.persistence.repository;

import com.um.catalogsync.sync.infrastructure.persistence.entity.SyncRunEntity;
import java.time.Instant;
import java.util.Optional;
import org.springframework.data.jpa.repository.JpaRepository;
import org.springframework.data.jpa.repository.Modifying;
import org.springframework.data.jpa.repository.Query;
import org.springframework.data.repository.query.Param;

/**
 * Repositorio Spring Data de las corridas. Detalle de infraestructura, no el
 * puerto: el puerto del dominio es {@code SyncRunRepository}.
 */
public interface JpaSyncRunRepository extends JpaRepository<SyncRunEntity, Long> {

    /**
     * La corrida que arranco ultima, para el reporte de estado (#28).
     *
     * <p>Ordena por {@code started_at} descendente, que es el indice que dejo
     * la migracion V2 ({@code ix_sync_run_started_at}), y desempata por id.
     * El desempate importa: dos corridas pueden arrancar en el mismo
     * microsegundo —la resolucion de {@code TIMESTAMPTZ}— y sin el, cual se
     * considera "la ultima" dependeria del plan de ejecucion.
     */
    Optional<SyncRunEntity> findFirstByOrderByStartedAtDescIdDesc();

    /**
     * Borra las corridas terminadas antes del limite, menos la mas reciente.
     *
     * <p><b>Sentencia escrita a mano y no un {@code deleteByFinishedAtBefore}
     * derivado</b> por dos razones. La primera es la excepcion: el metodo
     * derivado no puede expresar "menos la mas reciente", y sin eso un
     * servicio quieto mas tiempo que la ventana perderia la unica corrida que
     * el reporte tiene para mostrar. La segunda es el costo: el derivado
     * carga las entidades para borrarlas una por una, y esto es un solo
     * {@code DELETE}.
     *
     * <p><b>La mas reciente es la de id mas alto</b>, no la de
     * {@code started_at} mas alto. Son la misma fila —la columna es
     * {@code GENERATED BY DEFAULT AS IDENTITY}, asi que el id crece con el
     * orden de arranque— y el id no empata nunca, que es lo que hace a la
     * sentencia determinista.
     *
     * <p>Las corridas abiertas no entran: {@code finished_at} es nulo y la
     * comparacion las descarta sola. Los errores se van con su corrida por el
     * {@code ON DELETE CASCADE} de la FK, que es lo que permite que esta
     * sentencia no mencione {@code sync_error}: un {@code DELETE} masivo de
     * JPQL no dispara cascadas de JPA, pero esta cascada es de la base.
     */
    @Modifying
    @Query("""
            DELETE FROM SyncRunEntity r
            WHERE r.finishedAt < :limite
              AND r.id <> (SELECT MAX(ultima.id) FROM SyncRunEntity ultima)
            """)
    int purgarTerminadasAntesDe(@Param("limite") Instant limite);
}
